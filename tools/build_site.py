#!/usr/bin/env python3
"""Rebuild the whole site from stories/<slug>/ folders.

Every story lives in stories/<slug>/ with
    story.json        metadata: seq (int), title, subtitle, tag, blurb, lang, cover, cover_alt, optional cover_pos (CSS object-position for card crops)
    index.src.html    the page, with {{ROOT}} (path prefix to the site root) and {{HOME}} (link to the main page)

The story with the highest `seq` is the MAIN story: it is written to /index.html.
All others are the HISTORY: each is written to /history/<slug>/index.html, and /history/index.html
lists them as cards, newest first. Publishing a new story therefore automatically pins it as the main
and moves every previous main into the history. See tools/publish_story.py.

Posts (separate from stories): posts/sections.json defines sections such as "3ps"; each post is posts/<slug>/post.json
(section, seq, title, excerpt, cover, cover_alt, blocks). The newest post comes first. Each section is written to
/<section>/index.html and each post to /<section>/<slug>/index.html. Posts never pin or demote a story.

Usage:
    python3 tools/build_site.py            write the generated files
    python3 tools/build_site.py --check    exit 1 if generated files are out of date (used in CI)
    python3 tools/build_site.py --covers   also convert assets/source/<slug>-cover.png to assets/story/<slug>-cover.jpg
"""
import html
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STORIES = ROOT / "stories"
GENERATED_BANNER = "<!-- Generated by tools/build_site.py from stories/. Do not edit by hand. -->\n"

REQUIRED = ("seq", "title", "tag", "blurb", "lang", "cover", "cover_alt")


def esc(s):
    return html.escape(str(s), quote=True)


def load_stories():
    stories = []
    for meta in sorted(STORIES.glob("*/story.json")):
        d = json.loads(meta.read_text(encoding="utf-8"))
        d["slug"] = meta.parent.name
        missing = [k for k in REQUIRED if k not in d]
        if missing:
            sys.exit(f"{meta}: missing {', '.join(missing)}")
        if not (meta.parent / "index.src.html").exists():
            sys.exit(f"{meta.parent}: index.src.html is missing")
        if not (ROOT / d["cover"]).exists():
            sys.exit(f"{meta}: cover {d['cover']} does not exist")
        stories.append(d)
    if not stories:
        sys.exit("no stories found in stories/*/story.json")
    seqs = [s["seq"] for s in stories]
    if len(set(seqs)) != len(seqs):
        sys.exit(f"seq values must be unique, got {sorted(seqs)}")
    stories.sort(key=lambda s: -s["seq"])
    return stories


def card(story, prefix, href, cta):
    pos = f' style="object-position:{esc(story["cover_pos"])}"' if story.get("cover_pos") else ""
    return (
        f'<a class="card" href="{esc(href)}"><img src="{prefix}{esc(story["cover"])}" width="1536" height="1024"{pos} '
        f'alt="{esc(story["cover_alt"])}" loading="lazy" decoding="async"><div><span class="tag">{esc(story["tag"])}</span>'
        f'<h3>{esc(story["title"])}</h3><p>{esc(story["blurb"])}</p><span class="button">{esc(cta)}</span></div></a>'
    )


def history_section(stories, prefix):
    older = stories[1:]
    if not older:
        return ""
    cards = "".join(card(s, prefix, f"{prefix}history/{s['slug']}/", "Open the story ↗") for s in older)
    return (
        '<section class="prev" id="previous"><h2 class="sec" style="color:var(--gold);font-size:clamp(1.6rem,3.5vw,2.4rem);margin:0 0 6px">'
        'Previous stories</h2><p class="note" style="color:var(--mut);margin:0 0 6px">Every earlier main story is kept in the '
        f'<a href="{prefix}history/">history</a>.</p><div class="cards">{cards}</div></section>'
    )


def pinbar(main, prefix):
    return (
        '<div style="background:#201c25;border-bottom:1px solid #67503d;color:#c5b7a4;font:600 .8rem system-ui,sans-serif;'
        'padding:10px 18px;text-align:center">Archived story · '
        f'<a href="{prefix}" style="color:#efc17c">← Latest: {esc(main["title"])}</a> · '
        f'<a href="{prefix}history/" style="color:#efc17c">All stories</a> · <a href="{prefix}3ps/" style="color:#efc17c">3Ps</a></div>'
    )


def render_story(story, is_main, stories):
    src = (STORIES / story["slug"] / "index.src.html").read_text(encoding="utf-8")
    root = "" if is_main else "../../"
    home = "./" if is_main else "../../"
    out = src.replace("{{ROOT}}", root).replace("{{HOME}}", home)
    out = out.replace("<!--HISTORY_SECTION-->", history_section(stories, root) if is_main else "")
    if not is_main:
        i = out.index("<body")
        j = out.index(">", i) + 1
        out = out[:j] + pinbar(stories[0], root) + out[j:]
    # keep the doctype first, then the banner
    return out.replace("<!doctype html>", "<!doctype html>\n" + GENERATED_BANNER, 1) if out.lower().startswith("<!doctype html>") else GENERATED_BANNER + out


